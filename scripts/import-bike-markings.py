#!/usr/bin/env python3
"""Import the bicycle pavement marking outlines from FDOT Standard Plans Index
711-002 (Bicycle Markings), sheet 1:
python3 -I scripts/import-bike-markings.py PATH_TO_711-002.pdf
Needs poppler's pdftocairo on PATH; no Python packages. Writes
assets/markings/bike.js. See assets/markings/SOURCES.md.
"""
import json, pathlib, re, subprocess, sys, tempfile
ROOT = pathlib.Path(__file__).resolve().parents[1]
CURVE_STEPS = 12  # line segments per Bezier, as scripts/import-markings.py

def flatten(d):
    """Absolute M/L/C/Z path data (pdftocairo output) to closed polylines."""
    tokens = re.findall(r'[MLCZ]|-?\d*\.?\d+(?:e[-+]?\d+)?', d)
    rings, ring, i, at = [], [], 0, None
    while i < len(tokens):
        t = tokens[i]; i += 1
        if t == 'M':
            if len(ring) > 2: rings.append(ring)
            at = (float(tokens[i]), float(tokens[i + 1])); i += 2; ring = [at]
        elif t == 'L':
            at = (float(tokens[i]), float(tokens[i + 1])); i += 2; ring.append(at)
        elif t == 'C':
            c = [float(v) for v in tokens[i:i + 6]]; i += 6
            p0, p1, p2, p3 = at, (c[0], c[1]), (c[2], c[3]), (c[4], c[5])
            for k in range(1, CURVE_STEPS + 1):
                s = k / CURVE_STEPS; u = 1 - s
                ring.append(tuple(u*u*u*a + 3*u*u*s*b + 3*u*s*s*e + s*s*s*f for a, b, e, f in zip(p0, p1, p2, p3)))
            at = p3
        elif t == 'Z':
            if len(ring) > 2: rings.append(ring)
            ring = [at] if at else []
    if len(ring) > 2: rings.append(ring)
    return [r[:-1] if r[0] == r[-1] else r for r in rings]

def black_fills(pdf):
    with tempfile.TemporaryDirectory() as folder:
        out = pathlib.Path(folder) / 'page.svg'
        subprocess.run(['pdftocairo', '-svg', '-f', '1', '-l', '1', str(pdf), str(out)], check=True)
        source = out.read_text()
    shapes = []
    for attrs in re.findall(r'<path ([^>]*?)/>', source):
        if 'fill="rgb(0%, 0%, 0%)"' not in attrs or 'transform' in attrs: continue
        rings = flatten(re.search(r' d="([^"]*)"', attrs).group(1))
        xs = [p[0] for r in rings for p in r]; ys = [p[1] for r in rings for p in r]
        if xs: shapes.append({'rings': rings, 'box': (min(xs), min(ys), max(xs), max(ys))})
    return shapes

# Each detail's area on sheet 1 (PDF points), left to right: Shared Lane Marking,
# Helmeted Bicyclist Symbol, Bike Lane Arrow. Text and dimensions are excluded by
# size and by these areas.
AREAS = {'sharrow': (200, 150, 345, 470), 'bicyclist': (445, 205, 580, 405), 'bikeArrow': (685, 205, 775, 405)}

def main(pdf):
    shapes = [s for s in black_fills(pdf) if s['box'][3] - s['box'][1] > 8]
    picked = {name: [s for s in shapes if a[0] <= s['box'][0] and s['box'][2] <= a[2] and a[1] <= s['box'][1] and s['box'][3] <= a[3]]
              for name, a in AREAS.items()}
    box = lambda group: (min(s['box'][0] for s in group), min(s['box'][1] for s in group), max(s['box'][2] for s in group), max(s['box'][3] for s in group))
    # Scale: the Bike Lane Arrow is dimensioned 6'-0" long and 2'-0" wide.
    ax0, ay0, ax1, ay1 = box(picked['bikeArrow'])
    per_foot = (ay1 - ay0) / 6
    assert abs((ax1 - ax0) / per_foot - 2) < 0.05, 'arrow width check'
    data = {}
    for name, group in picked.items():
        x0, y0, x1, y1 = box(group)
        cx = (x0 + x1) / 2
        # Sheet y runs down with travel toward the top: marking y is feet forward from the near end.
        to = lambda p: [round((p[0] - cx) / per_foot, 4), round((y1 - p[1]) / per_foot, 4)]
        data[name] = {'source': f'FDOT Standard Plans Index 711-002 (FY 2025-26) sheet 1',
                      'width': round((x1 - x0) / per_foot, 3), 'length': round((y1 - y0) / per_foot, 3),
                      'shapes': [{'rule': 'evenodd', 'rings': [[to(p) for p in r] for r in s['rings']]} for s in group]}
    out = ROOT / 'assets/markings/bike.js'
    out.write_text('/* Generated by scripts/import-bike-markings.py; see assets/markings/SOURCES.md. */\n'
                   'Object.assign((globalThis.StripeMaker ??= {}).markingSymbols ??= {}, ' + json.dumps(data, separators=(',', ':')) + ');\n')
    for name, item in data.items(): print(name, item['width'], 'x', item['length'], 'ft,', len(item['shapes']), 'shapes')

if __name__ == '__main__':
    main(pathlib.Path(sys.argv[1]))
