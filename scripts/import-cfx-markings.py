#!/usr/bin/env python3
"""Import the artwork CFX's pavement symbols reuse from local sign faces:
python3 scripts/import-cfx-markings.py
Reads assets/signs/CFX-TM--standard.svg (CFX TM route marker, from the CFX 2026
Sign & Pavement Marking Design Details sheets 5-6) and assets/signs/R1-2--8924aa93d794.svg
(FHWA SHS R1-2 Yield, 36 in), and writes assets/markings/cfx.js. No dependencies.
See assets/markings/SOURCES.md.
"""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
TM = ROOT / 'assets/signs/CFX-TM--standard.svg'
YIELD = ROOT / 'assets/signs/R1-2--8924aa93d794.svg'

def paths(svg):
    """(fill, rings) for each <path>; the sign artwork is absolute M/L/Z only."""
    out = []
    for d, attrs in re.findall(r'<path d="([^"]+)"([^>]*)>', svg.read_text()):
        fill = re.search(r'fill="([^"]+)"', attrs).group(1)
        rings, ring = [], []
        for cmd, x, y in re.findall(r'([MLZ])\s*(?:(-?\d*\.?\d+)\s+(-?\d*\.?\d+))?', d):
            if cmd == 'M':
                if len(ring) > 2: rings.append(ring)
                ring = [(float(x), float(y))]
            elif cmd == 'L': ring.append((float(x), float(y)))
            elif cmd == 'Z':
                if len(ring) > 2: rings.append(ring)
                ring = []
        if len(ring) > 2: rings.append(ring)
        out.append((fill, [r[:-1] if r[0] == r[-1] else r for r in rings]))
    return out

def box(rings):
    xs = [p[0] for r in rings for p in r]; ys = [p[1] for r in rings for p in r]
    return min(xs), min(ys), max(xs), max(ys)

IN = 1 / 12
rnd = lambda v: round(v, 4)

# CFX toll route shield marking (CFX SPM Design Details sheet 47): the white
# field inside the 4" black border is 7'-0" wide, from the 4" black bar under
# the TOLL panel (182" from the near end) down to the shield's inner tip (6").
FIELD = {'x0': -42 * IN, 'x1': 42 * IN, 'y0': 6 * IN, 'y1': 182 * IN}
tm = paths(TM)
inner = next(rings for fill, rings in tm if fill == 'white' and box(rings)[0] > 3)   # white field of the face
bar = next(rings for fill, rings in tm if fill == 'black' and box(rings)[3] - box(rings)[1] < 3)  # bar under TOLL
florida = next(rings for fill, rings in tm if fill.lower() == '#f7921e')
digits = [rings for fill, rings in tm if fill == '#000000' and box(rings)[1] > box(bar)[3]]
fx0, _, fx1, fy1 = box(inner)
fy0 = box(bar)[3]
def to_field(p):
    # Sign x right, y down; marking x right of travel, y forward (the face's top is farthest).
    x = FIELD['x0'] + (p[0] - fx0) / (fx1 - fx0) * (FIELD['x1'] - FIELD['x0'])
    y = FIELD['y1'] - (p[1] - fy0) / (fy1 - fy0) * (FIELD['y1'] - FIELD['y0'])
    return [rnd(x), rnd(y)]
dx0, dy0, dx1, dy1 = box([r for rings in digits for r in rings])
numerals = to_field(((dx0 + dx1) / 2, (dy0 + dy1) / 2))

# CFX colored Yield (sheet 48): the R1-2 face stretched to 6'-0" x 13'-0", the
# point toward approaching traffic (the face's bottom point is nearest).
WIDTH, LENGTH = 6, 13
shapes = []
r12 = paths(YIELD)
x0, y0, x1, y1 = box(r12[0][1])
for fill, rings in r12:
    if fill.lower() == '#000000': continue  # the face's hairline edge
    shapes.append({'fill': fill.lower(), 'rings': [[[rnd((x - (x0 + x1) / 2) / (x1 - x0) * WIDTH), rnd((y1 - y) / (y1 - y0) * LENGTH)] for x, y in r] for r in rings]})

data = {
    'cfxFlorida': {'source': 'CFX TM route marker face (CFX 2026 SPM Design Details sheets 5-6), placed in the sheet 47 marking field',
                   'rings': [[to_field(p) for p in r] for r in florida], 'numerals': {'x': numerals[0], 'y': numerals[1]}},
    'cfxYield': {'source': 'FHWA SHS R1-2 Yield (36 in) stretched to CFX 2026 SPM Design Details sheet 48',
                 'width': WIDTH, 'length': LENGTH, 'shapes': shapes},
}
out = ROOT / 'assets/markings/cfx.js'
out.write_text('/* Generated by scripts/import-cfx-markings.py; see assets/markings/SOURCES.md. */\n'
               'Object.assign((globalThis.StripeMaker ??= {}).markingSymbols ??= {}, ' + json.dumps(data, separators=(',', ':')) + ');\n')
print(f'wrote {out.relative_to(ROOT)}')
